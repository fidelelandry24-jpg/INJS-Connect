-- À exécuter dans l’éditeur SQL Supabase après avoir vérifié le projet cible.
-- Ce script crée uniquement les tables de base pour les annonces et les modules.
-- Les comptes/rôles doivent être renforcés avant un déploiement public.

create table if not exists public.school_announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  category text not null default 'École',
  is_urgent boolean not null default false,
  published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.school_announcements enable row level security;

drop policy if exists "Lecture des annonces publiées" on public.school_announcements;
create policy "Lecture des annonces publiées"
on public.school_announcements for select
to anon, authenticated
using (published = true);

-- Important : cette politique autorise tout utilisateur connecté à publier.
-- Pour la production, remplacer par une politique fondée sur un rôle administrateur
-- stocké côté serveur et non choisi dans l’interface. Ne pas activer cette politique
-- permissive pour un site public.
drop policy if exists "Admin publie les annonces" on public.school_announcements;
create policy "Admin publie les annonces"
on public.school_announcements for insert
to authenticated
with check (false);

create table if not exists public.school_modules (
  id bigint generated by default as identity primary key,
  step_number int not null check (step_number between 1 and 7),
  title text not null,
  description text,
  route_key text unique,
  created_at timestamptz not null default now()
);

alter table public.school_modules enable row level security;
drop policy if exists "Lecture des modules" on public.school_modules;
create policy "Lecture des modules"
on public.school_modules for select
to anon, authenticated
using (true);

create table if not exists public.school_resources (
  id bigint generated by default as identity primary key,
  title text not null,
  resource_type text not null default 'Message',
  content text not null,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.school_resources enable row level security;
drop policy if exists "Lecture des ressources" on public.school_resources;
create policy "Lecture des ressources"
on public.school_resources for select
to authenticated
using (true);

